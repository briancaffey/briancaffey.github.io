#!/usr/bin/env python3
"""Restyle the contact-page portrait 160 ways with FLUX.3 Klein on the cluster.

Every variant is an image-to-image pass through black-forest-labs/flux-3-image-klein
running in the inference-club namespace. Requests go out ONE AT A TIME so that
only one GPU on the cluster is busy at any moment. Two backends are available:

  a1    flux3-klein-4090  the reference server, fp8, on node a1's RTX 4090  (default, ~28s)
  nim   flux3-klein-nim   NVIDIA NIM 1.0.1 on the DGX Spark node            (~46s)

Port-forward the one you want:
  kubectl -n inference-club port-forward svc/flux3-klein-4090 18001:8000 &
  kubectl -n inference-club port-forward svc/flux3-klein-nim  18000:8000 &

Then:  python3 scripts/portrait/generate.py [--backend a1|nim] [--only slug,slug] [--limit N]

Geometry note: the source is cropped to exact 4:3 and sent at 1024x768, which is
inside the NIM's 1,062,400-pixel ceiling and a multiple of 16 on both sides. The
model then does no internal reference resize, which is what used to shift the
subject's face between generations.
"""

import argparse
import base64
import io
import json
import os
import ssl
import sys
import time
import urllib.error
import urllib.request

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from styles import STYLES, prompt_for  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "public", "static", "JBC_PA.jpg")
OUT_DIR = os.path.join(ROOT, "public", "static", "contact", "portrait")
MANIFEST = os.path.join(ROOT, "app", "data", "portrait", "styles.ts")

GEN_W, GEN_H = 1024, 768          # native: no reference resize, no face drift
OUT_W, OUT_H = 1024, 768
WEBP_QUALITY = 76

BACKENDS = {
    "nim": {"key": "nim", "url": "http://127.0.0.1:18000", "steps": 24,
            "engine": "NVIDIA NIM 1.0.1", "model": "flux-3-image-klein",
            "node": "spark-d2ce", "precision": "bf16"},
    "a1": {"key": "a1", "url": "http://127.0.0.1:18001", "steps": 40,
           "engine": "reference server", "model": "flux-3-image-klein",
           "node": "a1", "precision": "fp8"},
}

SSL_CTX = ssl.create_default_context()
SSL_CTX.check_hostname = False
SSL_CTX.verify_mode = ssl.CERT_NONE


def source_b64():
    """Crop to exact 4:3 (losing 3px of height) then scale to the generation size."""
    src = Image.open(SRC).convert("RGB")
    w = src.width
    h = w * 3 // 4
    top = (src.height - h) // 2
    crop = src.crop((0, top, w, top + h))
    gen = crop.resize((GEN_W, GEN_H), Image.LANCZOS)
    buf = io.BytesIO()
    gen.save(buf, "PNG")
    return gen, base64.b64encode(buf.getvalue()).decode()


def post(url, body, timeout=900):
    req = urllib.request.Request(url, data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout, context=SSL_CTX) as r:
        return json.load(r)


def restyle(backend, b64, prompt, seed):
    """Returns (PIL image, seconds). Both backends speak their own dialect."""
    t0 = time.time()
    if backend["key"] == "nim":
        out = post(f"{backend['url']}/v1/infer", {
            "prompt": prompt, "image": f"data:image/png;base64,{b64}", "mode": "i2i",
            "width": GEN_W, "height": GEN_H, "steps": backend["steps"], "seed": seed,
            "resize_response_image": False,
        })
        payload = out["artifacts"][0]["base64"]
    else:
        out = post(f"{backend['url']}/v1/generate", {
            "prompt": prompt, "images": [f"data:image/png;base64,{b64}"],
            "width": GEN_W, "height": GEN_H, "steps": backend["steps"], "seed": seed,
            "return_b64": True, "upsample": False,
        })
        payload = out["b64_png"]
    if "," in payload[:64]:
        payload = payload.split(",", 1)[1]
    img = Image.open(io.BytesIO(base64.b64decode(payload))).convert("RGB")
    return img, time.time() - t0


def save(img, slug):
    os.makedirs(OUT_DIR, exist_ok=True)
    if img.size != (OUT_W, OUT_H):
        img = img.resize((OUT_W, OUT_H), Image.LANCZOS)
    path = os.path.join(OUT_DIR, slug + ".webp")
    img.save(path, "WEBP", quality=WEBP_QUALITY, method=5)
    return os.path.getsize(path)


def ts_escape(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")


def write_manifest(records):
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    order = {s[0]: i for i, s in enumerate(STYLES)}
    records = sorted(records, key=lambda r: order.get(r["slug"], 1e9))
    lines = [
        "// Generated by scripts/portrait/generate.py -- do not edit by hand.",
        "// Every image is an image-to-image pass through FLUX.3 Klein on the home cluster.",
        "",
        "export type PortraitStyle = {",
        "  slug: string",
        "  name: string",
        "  category: string",
        "  description: string",
        "  prompt: string",
        "  engine: string",
        "  model: string",
        "  node: string",
        "  precision: string",
        "  steps: number",
        "  seed: number",
        "  seconds: number",
        "}",
        "",
        "export const portraitStyles: PortraitStyle[] = [",
    ]
    for r in records:
        lines.append("  {")
        for key in ("slug", "name", "category", "description", "prompt",
                    "engine", "model", "node", "precision"):
            lines.append(f"    {key}: '{ts_escape(r[key])}',")
        lines.append(f"    steps: {r['steps']},")
        lines.append(f"    seed: {r['seed']},")
        lines.append(f"    seconds: {r['seconds']:.1f}")
        lines.append("  },")
    lines.append("]")
    lines.append("")
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--seed", type=int, default=20261115)
    ap.add_argument("--backend", default="a1", choices=sorted(BACKENDS))
    args = ap.parse_args()

    backend = BACKENDS[args.backend]
    wanted = {s.strip() for s in args.only.split(",") if s.strip()}
    todo = [s for s in STYLES if not wanted or s[0] in wanted]
    if args.limit:
        todo = todo[:args.limit]

    gen, b64 = source_b64()
    os.makedirs(OUT_DIR, exist_ok=True)
    save(gen, "original")
    print(f"source cropped to exact 4:3 and sent at {GEN_W}x{GEN_H}")
    print(f"{len(todo)} styles, one request at a time, on {backend['key']} "
          f"({backend['node']}, {backend['steps']} steps)\n")

    records, failures = [], []
    t0 = time.time()
    for i, (slug, name, category, medium) in enumerate(todo):
        prompt = prompt_for(medium)
        seed = args.seed + i
        for attempt in (1, 2):
            try:
                img, secs = restyle(backend, b64, prompt, seed)
                size = save(img, slug)
                records.append({
                    "slug": slug, "name": name, "category": category,
                    "description": medium, "prompt": prompt,
                    "engine": backend["engine"], "model": backend["model"],
                    "node": backend["node"], "precision": backend["precision"],
                    "steps": backend["steps"], "seed": seed, "seconds": secs,
                })
                eta = (time.time() - t0) / len(records) * (len(todo) - len(records)) / 60
                print(f"[{i+1:3d}/{len(todo)}] {slug:<22} {size/1024:6.1f} KB "
                      f"{secs:5.1f}s  eta {eta:4.1f}m  {name}", flush=True)
                break
            except Exception as e:  # noqa: BLE001 - log it and keep the run going
                if attempt == 2:
                    failures.append((slug, repr(e)))
                    print(f"        {slug:<22} FAILED {e!r}", flush=True)
                else:
                    time.sleep(5)

    write_manifest(records)
    total = sum(os.path.getsize(os.path.join(OUT_DIR, f)) for f in os.listdir(OUT_DIR))
    print(f"\n{len(records)} styles in {(time.time()-t0)/60:.1f} min, "
          f"{total/1024/1024:.1f} MB on disk")
    if failures:
        print(f"{len(failures)} failed: " + ", ".join(s for s, _ in failures))
        sys.exit(1)


if __name__ == "__main__":
    main()
